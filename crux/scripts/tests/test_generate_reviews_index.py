def _load_script():
    """The regenerator, imported by path under its own module name.

    The file is not an importable module name (it carries hyphens), so every
    in-process case loads it this way. `AtomicWriteBackstopTestCase` does the
    same inline; this is the shared form for the cases added since.
    """
    spec = importlib.util.spec_from_file_location("_reviews_index_probe", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

EMPTY_INDEX = """# Decision reviews

<!-- Generated by crux/scripts/generate-reviews-index.py — do not hand-edit. -->

One row per historical decision-review report, newest first. Each dated report is hand-kept; this index is derived from the reports in this directory.

| date | raised | standing | dismissed | report |
|------|--------|----------|-----------|--------|

Reports: 0
"""


def _dismissed_block(dismissed) -> str:
    if not dismissed:
        return "dismissed: []"
    return "dismissed:\n" + "".join(f'  - "{d}"\n' for d in dismissed).rstrip()


def _report(date: str, findings: list[str], dismissed: list[str],
            grammar: str | None = None) -> str:
    """A report carrying no `report_grammar` key — a LEGACY report by default.

    Its `raised` is the frozen legacy count: the number of distinct
    `adr-review-<slug>` tokens below the frontmatter, wherever they occur.
    Pass `grammar` to declare a discriminator instead.
    """
    block = _dismissed_block(dismissed)
    keys = f"type: adr-review\ndate: {date}\n"
    if grammar is not None:
        keys += f"report_grammar: {grammar}\n"
    body = "\n".join(f"### Finding `{f}`\n\nSomething about a decision.\n" for f in findings)
    return f"---\n{keys}{block}\n---\n\n# Review {date}\n\n{body}"


def _lifecycle(date: str, *, findings=(), records=(), notes=(), dismissed=(),
               summary_rows=None) -> str:
    """A report under the lifecycle grammar, six sections and a summary table.

    `findings` are the ids defined by `### ` entries under `## Propose`.
    `summary_rows` defaults to `findings`, because the postcondition requires
    the summary-table row id set to EQUAL the defined set; pass it explicitly
    to build a report that violates that.
    `records` are `(source_date, finding_id, pass, event, locator)` tuples
    rendered into the lifecycle table under `## Coverage`.
    `notes` are `(finding_id, kind, pass)` tuples rendered inside that
    finding's own entry, where a note lives.
    """
    rows = list(findings) if summary_rows is None else list(summary_rows)
    out = [f"---\ntype: adr-review\ndate: {date}\nreport_grammar: lifecycle\n"
           f"{_dismissed_block(dismissed)}\n---\n",
           f"# Decision review \u2014 {date}\n",
           "| finding id | section | objective | proposed act | size |",
           "|---|---|---|---|---|"]
    for fid in rows:
        out.append(f"| `{fid}` | Propose | OBJ-1 | write an ADR | patch |")
    out.append("")
    out.append("## Propose")
    out.append("")
    for fid in findings:
        out.append(f"### `{fid}` \u2014 a fixture finding")
        out.append("")
        out.append("Body prose about one decision.")
        for note_id, kind, ordinal in notes:
            if note_id == fid:
                out.append(f"- **{kind}, pass {ordinal}** \u2014 prose about the event.")
        out.append("")
    out += ["## Amend", "", "## Repair", "", "## Revoke", "", "## Keep", "",
            "## Coverage", ""]
    if records:
        out.append("| source report date | finding id | pass | event | locator |")
        out.append("|---|---|---|---|---|")
        for src, fid, ordinal, event, locator in records:
            out.append(f"| {src} | `{fid}` | {ordinal} | {event} | {locator} |")
        out.append("")
    return "\n".join(out) + "\n"


class _Harness(unittest.TestCase):
    """The miniature repo root and the CLI driver. Carries no test of its own."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        (self.root / ".bionic.yml").write_text(
            'config_version: "1"\ndocs_dir: bionic\n', encoding="utf-8")
        self.reviews = self.root / "bionic" / "adrs" / "reviews"
        self.reviews.mkdir(parents=True)

    def run_cli(self, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--repo-root", str(self.root), *args],
            capture_output=True, text=True)

    def write(self, name: str, text: str) -> None:
        (self.reviews / name).write_text(text, encoding="utf-8")

    def index_bytes(self) -> bytes | None:
        """The on-disk index bytes, or None when no index exists."""
        index = self.reviews / "index.md"
        return index.read_bytes() if index.exists() else None

    def assert_resolver_finding(self, result, *fragments) -> str:
        """The resolver's DOCUMENT lane: exit 1, one finding naming resolver.json.

        Asserts the exit, that the one `validation_errors` entry names
        `bionic/adrs/summaries/resolver.json`, every reason fragment, no
        absolute path in the reason, empty `orphan_rows` in `--dry-run`, and
        no shared authority refusal on stderr. Returns the reason.
        """
        self.assertEqual(result.returncode, 1, (result.stdout, result.stderr))
        payload = json.loads(result.stdout)
        errors = payload["validation_errors"]
        self.assertEqual([e["file"] for e in errors], [RESOLVER_FILE], errors)
        for fragment in fragments:
            self.assertIn(fragment, errors[0]["error"])
        self.assertNotIn(str(self.root), errors[0]["error"])
        if "drift" in payload:
            self.assertEqual((payload["drift"], payload["orphan_rows"]), (False, []))
        else:
            self.assertIsNone(payload["written"])
        self.assertNotIn("migration-", result.stderr)
        self.assertNotIn("Traceback", result.stderr)
        return errors[0]["error"]


#: The resolver's `validation_errors` file key in every harness tree.
